function both() {
  document.getElementById('panes').innerHTML =
    '<div class="pane"><div class="lab">DARK</div>' + frame('dark') + '</div>' +
    '<div class="pane"><div class="lab">LIGHT</div>' + frame('light') + '</div>';
}
let showing = 'dark';
function one() {
  document.getElementById('panes').innerHTML = '<div class="pane"><div class="lab" id="lab">DARK</div><div class="stack" style="width:' + W + 'px;height:' + H + 'px">' + frame('dark') + frame('light') + '</div></div>';
  const [dk, lt] = document.querySelectorAll('.stack iframe');
  lt.style.opacity = showing === 'light' ? 1 : 0; dk.style.opacity = showing === 'dark' ? 1 : 0;
  document.getElementById('lab').textContent = showing.toUpperCase();
}
document.getElementById('m-both').onclick = () => { both(); set('m-both'); document.getElementById('flip').style.display = 'none'; };
document.getElementById('m-switch').onclick = () => { one(); set('m-switch'); document.getElementById('flip').style.display = ''; };
