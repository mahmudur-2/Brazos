document.getElementById('title').textContent = d.name;
document.title = 'BRAZOS — ' + d.name + ' — dark and light';
const i = ORDER.indexOf(key);
document.getElementById('prev').href = 'view.html?key=' + ORDER[(i - 1 + ORDER.length) % ORDER.length];
document.getElementById('next').href = 'view.html?key=' + ORDER[(i + 1) % ORDER.length];
