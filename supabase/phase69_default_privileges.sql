-- Brazos - Phase 69 (optional) - stop the default EXECUTE grant recurring
--
-- Paste into Supabase - SQL Editor and run. Safe to re-run (idempotent).
--
-- SEPARATE FILE ON PURPOSE. phase69_execute_privilege_lockdown.sql fixes the
-- sixteen functions that already drifted. This one changes what happens to
-- functions created in future, which is a standing policy change rather than a
-- repair, so it can be declined without affecting phase69 or phase68. Applying
-- it is NOT a precondition for either.
--
-- ===========================================================================
-- WHAT IT DOES
-- ===========================================================================
-- For functions, the CREATE-time default ACL grants EXECUTE to PUBLIC. That is
-- how sixteen functions in schema public ended up reachable by `anon` without
-- anyone granting anything, and it is what aborted phase68 at its self-check
-- (d). This removes that default for functions created from here on by the role
-- that runs this statement.
--
-- Relationship to phase32: phase32_function_execute_privileges.sql:82-89
-- already sets the same thing, but qualified `for role postgres`, which applies
-- only to objects created by postgres. The statement below carries no `for
-- role` clause, so it applies to the CURRENT role. Run it as the role your
-- migrations actually run as. If that is postgres, this is belt and braces over
-- phase32 and changes nothing; if migrations ever run as another role, this is
-- the line that covers it.
--
-- Not retroactive. It has no effect on any function that already exists -
-- that is exactly why phase69_execute_privilege_lockdown.sql has to name all
-- sixteen explicitly.
--
-- ===========================================================================
-- THE COST
-- ===========================================================================
-- After this, a new function is executable by nobody but its owner until its
-- migration says otherwise. A migration that creates a function and forgets its
-- grants produces a function the app cannot call - a loud, immediate failure at
-- the first call, rather than a silent over-grant nobody notices for thirty
-- phases. That trade is the point. CLAUDE.md carries the matching rule: every
-- new SECURITY DEFINER function in schema public ships its REVOKE/GRANT in the
-- same migration that creates it.

alter default privileges in schema public revoke execute on functions from public;
